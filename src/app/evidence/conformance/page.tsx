function Stat({
  value,
  label,
  detail,
  tone,
}: {
  value: number;
  label: string;
  detail: string;
  tone?: 'good' | 'bad';
}) {
  const valueColor = tone === 'bad' ? 'text-red-600' : tone === 'good' ? 'text-emerald-600' : 'text-slate-900';
  return (
    <div className="rounded-xl border border-slate-200 bg-slate-50/60 p-4 flex flex-col">
      <span className={`text-2xl font-extrabold tabular-nums ${valueColor}`}>{value}</span>
      <span className="text-xs font-semibold text-slate-600 mt-1">{label}</span>
      <span className="text-[11px] text-slate-400 mt-1.5 leading-snug">{detail}</span>
    </div>
  );
}
