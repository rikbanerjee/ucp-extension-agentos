const payload = getConformancePayload();

function CoverageBadge({ covered }: { covered: boolean }) {
  return covered ? (
    <span className="inline-flex items-center gap-1 text-xs font-semibold px-2 py-0.5 rounded-full border bg-emerald-50 text-emerald-700 border-emerald-200">
      ✅ covered
    </span>
  ) : (
    <span className="inline-flex items-center gap-1 text-xs font-semibold px-2 py-0.5 rounded-full border bg-red-50 text-red-700 border-red-200">
      🔴 uncovered
    </span>
  );
}

function ArchetypeCellBadge({
  cell,
}: {
  cell: (typeof ARCHETYPE_GRID)[number]['cells'][keyof (typeof ARCHETYPE_GRID)[number]['cells']];
}) {
  if (cell.exercised === null) {
    return <span className="text-xs text-slate-400 italic">not derived</span>;
  }
  if (cell.exercised) {
    return (
      <span className="inline-flex items-center gap-1 text-xs font-semibold text-emerald-700">
        ✅
        {cell.namespaces.length > 0 && (
          <span className="font-normal text-slate-400"> {cell.namespaces.length} ns</span>
        )}
      </span>
    );
  }
  return <span className="text-xs font-semibold text-slate-300">—</span>;
}

